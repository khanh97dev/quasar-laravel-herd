import fs from 'node:fs'
import fsp from 'node:fs/promises'
import path from 'node:path'
import { paths } from '../core/paths.js'
import { IS_WIN, EXE } from '../core/platform.js'
import { run, which, isExecutable } from '../core/shell.js'
import { settings } from '../core/config.js'
import { log } from '../core/logger.js'
import { upstreamServers } from '../services/php.js'
import { certFiles } from './ssl.js'

export async function binary () {
  const bundled = path.join(paths.runtimes, 'nginx', `nginx${EXE}`)
  if (isExecutable(bundled) || (IS_WIN && fs.existsSync(bundled))) return bundled
  return which('nginx')
}

export function confFile () {
  return path.join(paths.nginxConf, 'nginx.conf')
}

/**
 * The main config is regenerated on every start so it always matches current
 * settings; per-site files live in sites/ and are included wholesale.
 */
export async function writeMainConfig () {
  const { httpPort } = settings.all()
  const mime = await mimeTypesPath()

  const conf = `
# Generated by Quasar Herd — do not edit, changes are overwritten on restart.
# A local dev server does not need one worker per core.
worker_processes 2;
daemon off;
pid ${posix(path.join(paths.run, 'nginx.pid'))};
error_log ${posix(path.join(paths.logs, 'nginx-error.log'))} warn;

events { worker_connections 1024; }

http {
  ${mime ? `include ${posix(mime)};` : ''}
  default_type application/octet-stream;

  access_log ${posix(path.join(paths.logs, 'nginx-access.log'))};
  client_body_temp_path ${posix(path.join(paths.tmp, 'nginx-body'))};
  proxy_temp_path ${posix(path.join(paths.tmp, 'nginx-proxy'))};
  fastcgi_temp_path ${posix(path.join(paths.tmp, 'nginx-fastcgi'))};
  uwsgi_temp_path ${posix(path.join(paths.tmp, 'nginx-uwsgi'))};
  scgi_temp_path ${posix(path.join(paths.tmp, 'nginx-scgi'))};

  sendfile on;
  tcp_nopush on;
  keepalive_timeout 65;
  client_max_body_size 256M;
  server_names_hash_bucket_size 128;
  absolute_redirect off;

  # Long timeouts: a debugger session must not be cut off mid-breakpoint.
  fastcgi_read_timeout 3600s;
  fastcgi_send_timeout 3600s;
  fastcgi_buffers 16 64k;
  fastcgi_buffer_size 128k;

  server {
    listen ${httpPort} default_server;
    server_name _;
    root ${posix(path.join(paths.config, 'default'))};
    location / { return 404 'No site is parked for this host.'; default_type text/plain; }
  }

  include ${posix(path.join(paths.nginxSites, '*.conf'))};
}
`.trimStart()

  await fsp.mkdir(path.join(paths.config, 'default'), { recursive: true })
  await fsp.writeFile(confFile(), conf)
  return confFile()
}

async function mimeTypesPath () {
  const candidates = [
    path.join(paths.runtimes, 'nginx', 'conf', 'mime.types'),
    '/etc/nginx/mime.types',
    '/usr/local/nginx/conf/mime.types'
  ]
  for (const file of candidates) if (fs.existsSync(file)) return file
  return null
}

/** nginx wants forward slashes even on Windows. */
function posix (p) {
  return p.replace(/\\/g, '/')
}

export async function writeSiteConfig (site) {
  const { tld, httpPort, httpsPort } = settings.all()
  const domain = site.domain || `${site.name}.${tld}`
  const root = site.root
  const version = site.php || settings.get('defaultPhp')
  const upstream = `php_${version.replace(/\W/g, '_')}`
  const servers = upstreamServers(version)
  const index = site.type === 'laravel' || site.type === 'generic' ? 'index.php index.html' : 'index.html index.php'

  const ssl = site.secure ? certFiles(domain) : null
  if (ssl && !fs.existsSync(ssl.crt)) {
    throw new Error(`Certificate for ${domain} is missing — issue it before enabling HTTPS.`)
  }

  const documentRoot = site.publicPath ? path.join(root, site.publicPath) : root

  const conf = `
# ${domain} — generated by Quasar Herd
upstream ${upstream} {
${servers.map(s => `  server ${s};`).join('\n')}
}

${site.secure
  ? `server {
  listen ${httpPort};
  server_name ${domain} *.${domain};
  return 301 https://$host$request_uri;
}
`
  : ''}
server {
  ${site.secure
    ? `listen ${httpsPort} ssl;
  http2 on;
  ssl_certificate ${posix(ssl.crt)};
  ssl_certificate_key ${posix(ssl.key)};
  ssl_protocols TLSv1.2 TLSv1.3;`
    : `listen ${httpPort};`}

  server_name ${domain} *.${domain};
  root ${posix(documentRoot)};
  index ${index};
  charset utf-8;

  access_log ${posix(path.join(paths.logs, `site-${domain}-access.log`))};
  error_log ${posix(path.join(paths.logs, `site-${domain}-error.log`))};

  location = /favicon.ico { access_log off; log_not_found off; }
  location = /robots.txt  { access_log off; log_not_found off; }

  location / {
    try_files $uri $uri/ ${site.type === 'static' ? '=404' : '/index.php?$query_string'};
  }

  location ~ \\.php$ {
    try_files $uri =404;
    fastcgi_split_path_info ^(.+\\.php)(/.+)$;
    fastcgi_pass ${upstream};
    fastcgi_index index.php;
    include ${posix(await fastcgiParamsPath())};
    fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
    fastcgi_param PATH_INFO $fastcgi_path_info;
    fastcgi_param HTTPS ${site.secure ? 'on' : 'off'};
    fastcgi_param HERD_SITE ${domain};
    fastcgi_param HERD_PHP_VERSION ${version};
  }

  location ~ /\\.(?!well-known).* { deny all; }
}
`.trimStart()

  const file = path.join(paths.nginxSites, `${domain}.conf`)
  await fsp.writeFile(file, conf)
  return file
}

/**
 * Bundled nginx on Windows ships fastcgi_params; on Linux the distro provides
 * it. If neither exists we write our own so the config never dangles.
 */
async function fastcgiParamsPath () {
  const candidates = [
    path.join(paths.runtimes, 'nginx', 'conf', 'fastcgi_params'),
    '/etc/nginx/fastcgi_params'
  ]
  for (const file of candidates) if (fs.existsSync(file)) return file

  const own = path.join(paths.nginxConf, 'fastcgi_params')
  if (!fs.existsSync(own)) {
    await fsp.writeFile(own, [
      'fastcgi_param QUERY_STRING $query_string;',
      'fastcgi_param REQUEST_METHOD $request_method;',
      'fastcgi_param CONTENT_TYPE $content_type;',
      'fastcgi_param CONTENT_LENGTH $content_length;',
      'fastcgi_param SCRIPT_NAME $fastcgi_script_name;',
      'fastcgi_param REQUEST_URI $request_uri;',
      'fastcgi_param DOCUMENT_URI $document_uri;',
      'fastcgi_param DOCUMENT_ROOT $document_root;',
      'fastcgi_param SERVER_PROTOCOL $server_protocol;',
      'fastcgi_param REQUEST_SCHEME $scheme;',
      'fastcgi_param GATEWAY_INTERFACE CGI/1.1;',
      'fastcgi_param SERVER_SOFTWARE nginx/$nginx_version;',
      'fastcgi_param REMOTE_ADDR $remote_addr;',
      'fastcgi_param REMOTE_PORT $remote_port;',
      'fastcgi_param SERVER_ADDR $server_addr;',
      'fastcgi_param SERVER_PORT $server_port;',
      'fastcgi_param SERVER_NAME $server_name;',
      'fastcgi_param REDIRECT_STATUS 200;'
    ].join('\n'))
  }
  return own
}

export async function removeSiteConfig (domain) {
  await fsp.rm(path.join(paths.nginxSites, `${domain}.conf`), { force: true })
}

export async function test () {
  const bin = await binary()
  if (!bin) return { ok: false, output: 'nginx is not installed.' }
  const { code, stdout, stderr } = await run(bin, ['-t', '-c', confFile(), '-p', paths.root], { allowFailure: true })
  return { ok: code === 0, output: stderr || stdout }
}

export async function reload () {
  const bin = await binary()
  if (!bin) throw new Error('nginx is not installed.')
  const { code, stderr } = await run(bin, ['-s', 'reload', '-c', confFile(), '-p', paths.root], { allowFailure: true })
  if (code !== 0) log.warn('nginx', `reload failed, caller should restart: ${stderr}`)
  return code === 0
}
